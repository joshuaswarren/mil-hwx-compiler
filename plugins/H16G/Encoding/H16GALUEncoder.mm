typedef struct {
    NSUInteger size;
    const uint32_t *words;
    NSUInteger wordCount;
    uint32_t formatCode;
    NSUInteger selectorOffset;
} ALUGeometry;

static const ALUGeometry kGeometries[] = {
    {128,kALU128Words,sizeof(kALU128Words)/4,0x01,0xcc},
    {256,kALU256Words,sizeof(kALU256Words)/4,0x05,0xb8},
    {512,kALU512Words,sizeof(kALU512Words)/4,0x17,0xcc},
    {1024,kALU1024Words,sizeof(kALU1024Words)/4,0x5c,0xcc},
    {2048,kALU2048Words,sizeof(kALU2048Words)/4,0x170,0xcc},
};

static const ALUGeometry *geometry(NSUInteger size) {
    for (const ALUGeometry &row : kGeometries)
        if (row.size == size) return &row;
    return NULL;
}

static BOOL opcodeForName(NSString *name,uint8_t *opcode) {
    if ([name isEqualToString:@"add"]) *opcode=0x00;
    else if ([name isEqualToString:@"mul"] || [name isEqualToString:@"multiply"])
        *opcode=0x04;
    else if ([name isEqualToString:@"max"]) *opcode=0x08;
    else if ([name isEqualToString:@"min"]) *opcode=0x0c;
    else return NO;
    return YES;
}

@implementation H16GALUEncoder
+ (BOOL)supportsOperationName:(NSString *)operationName squareSize:(NSUInteger)size {
    uint8_t opcode=0;
    return geometry(size) != NULL && opcodeForName(operationName,&opcode);
}
+ (H16GEncodedTDProgram *)encodeOperationName:(NSString *)operationName
                                   squareSize:(NSUInteger)size
                                        error:(NSError **)error {
    const ALUGeometry *row=geometry(size);uint8_t opcode=0;
    if (!row || !opcodeForName(operationName,&opcode)) {
        if (error) *error=[NSError errorWithDomain:H16GALUEncoderErrorDomain
            code:1 userInfo:@{NSLocalizedDescriptionKey:
            @"binary fp16 ALU requires add/mul/max/min and square N in {128,256,512,1024,2048}"}];
        return nil;
    }
    NSMutableData *data=[NSMutableData dataWithBytes:row->words
        length:row->wordCount*sizeof(uint32_t)];
    ((uint8_t *)data.mutableBytes)[row->selectorOffset]=opcode;
    return [[H16GEncodedTDProgram alloc] initWithData:data
        kernelRelocationOffsets:@[] programRecordCount:16
        programFormatCode:row->formatCode scratchByteLength:0];
}
@end
