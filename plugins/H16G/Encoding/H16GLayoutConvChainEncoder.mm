static BOOL containsOffset(const NSUInteger *offsets, NSUInteger count,
                           NSUInteger offset) {
    for (NSUInteger i = 0; i < count; ++i)
        if (offsets[i] == offset) return YES;
    return NO;
}

static BOOL writeInvariantRecipe(H16GTDWriter *writer,
                                 const uint32_t *recipe,
                                 NSUInteger recipeCount,
                                 const NSUInteger *derivedOffsets,
                                 NSUInteger derivedCount,
                                 NSError **error) {
    for (NSUInteger i = 0; i < recipeCount; ++i) {
        NSUInteger offset = i * sizeof(uint32_t);
        uint32_t value = recipe[i];
        if (value == 0 || containsOffset(derivedOffsets, derivedCount, offset))
            continue;
        NSString *field = [NSString stringWithFormat:
            @"layout_conv.packet.0x%03lx", (unsigned long)offset];
        if (![writer writeUInt32:value atOffset:offset field:field error:error])
            return NO;
    }
    return YES;
}

static BOOL put(H16GTDWriter *writer, NSUInteger offset, uint64_t value,
                NSString *field, NSError **error) {
    if (value > UINT32_MAX) {
        if (error) *error = [NSError errorWithDomain:H16GTDWriterErrorDomain
            code:12 userInfo:@{NSLocalizedDescriptionKey:
                [NSString stringWithFormat:@"field '%@' exceeds H16G u32", field]}];
        return NO;
    }
    return [writer writeUInt32:(uint32_t)value atOffset:offset
                         field:field error:error];
}

static BOOL writeTapTable(H16GTDWriter *writer, NSUInteger start,
                          uint32_t step, NSError **error) {
    for (NSUInteger i = 0; i < 31; ++i) {
        uint32_t value = i < 15 ? (uint32_t)(i + 1) * step : step;
        if (![writer writeUInt32:value atOffset:start + i * 4
                           field:@"layout_conv.weight_tap" error:error])
            return NO;
    }
    return YES;
}

