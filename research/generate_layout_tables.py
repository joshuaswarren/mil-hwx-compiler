#!/usr/bin/env python3
"""Generate the H13 layout template table from oracle captures.

reshape and squeeze are pure views to the frontend, but Apple mints real
data-movement programs for them when the view is the returned surface.
Each decoded capture becomes one entry keyed by (operation, input CHW,
output CHW) with the words replayed verbatim. The constant section is
verified all-zero and emitted as a size the encoder memsets.

Captures live at research/oracles/h13/layout_<op>_*.json (probe receipts);
their tensor_descriptors carry the normalized [1,C,H,W] surfaces the
support check keys on.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CAPTURES = ROOT / "research" / "oracles" / "h13"
OPERATIONS = {"reshape": 0, "squeeze": 1}


def reconstruct_task(td):
    words = [int(w, 16) for w in td["header_words"]]
    flat = {}
    for block in td["blocks"].values():
        for a, v in block["words"].items():
            flat[int(a, 16)] = int(v, 16)
    for rec in td["records"]:
        words.append(int(rec["header"], 16))
        base = int(rec["address"], 16)
        for index in range(rec["count"]):
            words.append(flat[base + index * 4])
    return words


def derive(path):
    record = json.loads(path.read_text())
    if record.get("error") or not record.get("task_descriptors"):
        return None
    op = record["parameters"]["operation"]
    if op not in OPERATIONS:
        raise SystemExit(f"{path.name}: unmapped operation {op}")
    descriptors = record["tensor_descriptors"]
    if len(descriptors) != 2:
        raise SystemExit(f"{path.name}: want 2 surface descriptors")
    in_shape = descriptors[0]["shape"]
    out_shape = descriptors[1]["shape"]
    if len(in_shape) != 4 or len(out_shape) != 4:
        raise SystemExit(f"{path.name}: descriptors are not [1,C,H,W]")
    if in_shape[0] != 1 or out_shape[0] != 1:
        raise SystemExit(f"{path.name}: batch dim is not 1")
    tasks = [reconstruct_task(t) for t in record["task_descriptors"]]
    words = [w for task in tasks for w in task]
    const = record["constant_section"]
    if const["nonzero_bytes"] != 0:
        raise SystemExit(f"{path.name}: constant section is not all-zero")
    return {
        "op": OPERATIONS[op],
        "words": words,
        "sizes": [len(t) for t in tasks],
        "constant_bytes": const["size"],
        "in": in_shape[1:],
        "out": out_shape[1:],
    }


def words_literal(name, words):
    lines = [f"static const uint32_t {name}[] = {{"]
    for off in range(0, len(words), 6):
        chunk = words[off:off + 6]
        lines.append("    " + ", ".join(f"0x{w:08x}" for w in chunk) + ",")
    lines.append("};")
    return lines


def main():
    entries = []
    for path in sorted(CAPTURES.glob("layout_*.json")):
        entry = derive(path)
        if entry is None:
            continue
        entry["stem"] = path.stem
        entries.append(entry)
    if not entries:
        raise SystemExit("no layout captures decoded")
    print(f"verified {len(entries)} entries")

    out = ["// Generated by research/generate_layout_tables.py from",
           "// research/oracles/h13/layout_*.json — do not edit by hand.",
           "#pragma once",
           "",
           "struct H13LayoutTemplate {",
           "    std::uint8_t operation;",
           "    std::uint32_t inChannels, inHeight, inWidth;",
           "    std::uint32_t outChannels, outHeight, outWidth;",
           "    const std::uint32_t *words;",
           "    std::size_t wordCount;",
           "    std::size_t constantBytes;",
           "    const std::uint32_t *taskWords;",
           "    std::size_t taskCount;",
           "};",
           ""]
    table = []
    for index, entry in enumerate(entries):
        wname = f"kLayoutWords{index}"
        sname = f"kLayoutSizes{index}"
        out.extend(words_literal(wname, entry["words"]))
        out.append(f"static const uint32_t {sname}[] = "
                   f"{{{', '.join(map(str, entry['sizes']))}}};")
        out.append("")
        in_c, in_h, in_w = entry["in"]
        out_c, out_h, out_w = entry["out"]
        table.append(
            "    {%d, %d, %d, %d, %d, %d, %d, %s, std::size(%s), %d, "
            "%s, std::size(%s)},"
            % (entry["op"], in_c, in_h, in_w, out_c, out_h, out_w,
               wname, wname, entry["constant_bytes"], sname, sname))
    out.append("static const H13LayoutTemplate kLayoutTasks[] = {")
    out.extend("    " + row for row in table)
    out.append("};")
    destination = ROOT / "plugins" / "H13" / "H13LayoutTemplates.inc"
    destination.write_text("\n".join(out) + "\n")
    print(f"wrote {destination}")


if __name__ == "__main__":
    main()
