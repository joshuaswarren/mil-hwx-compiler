#!/usr/bin/env python3
"""Generate the H13 concat template table from oracle captures.

Every non-interleave concat axis decodes to the same two-task data-movement
program with identical channel bindings; only tile_dma_dst geometry words
change. Each decoded capture therefore becomes one entry keyed by
(axis, input CHW, second-input CHW, output CHW) with the words replayed
verbatim. interleave=true mints a separate three-task family and is excluded
until that template is implemented.

Captures live at research/oracles/h13/layout_concat_*.json (probe receipts);
their tensor_descriptors carry [in0, in1, out] as normalized [1,C,H,W]
surfaces.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CAPTURES = ROOT / "research" / "oracles" / "h13"
AXIS = re.compile(r"^layout_concat_ax(\d+)_")


def reconstruct_task(td):
    words = [int(w, 16) for w in td["header_words"]]
    flat = {}
    for block in td["blocks"].values():
        for a, v in block["words"].items():
            flat[int(a, 16)] = int(v, 16)
    for rec in td["records"]:
        words.append(int(rec["header"], 16))
        base = int(rec["address"], 16)
        for index in range(rec["count"]):
            words.append(flat[base + index * 4])
    return words


def derive(path):
    match = AXIS.match(path.name)
    if not match or "_il_" in path.name:
        return None
    record = json.loads(path.read_text())
    if record.get("error") or not record.get("task_descriptors"):
        return None
    if record["parameters"].get("operation") != "concat":
        return None
    descriptors = record["tensor_descriptors"]
    if len(descriptors) != 3:
        raise SystemExit(f"{path.name}: want 3 surface descriptors")
    shapes = [d["shape"] for d in descriptors]
    if any(len(s) != 4 or s[0] != 1 for s in shapes):
        raise SystemExit(f"{path.name}: descriptors are not [1,C,H,W]")
    tasks = [reconstruct_task(t) for t in record["task_descriptors"]]
    words = [w for task in tasks for w in task]
    const = record["constant_section"]
    if const["nonzero_bytes"] != 0:
        raise SystemExit(f"{path.name}: constant section is not all-zero")
    return {
        "axis": int(match.group(1)),
        "words": words,
        "sizes": [len(t) for t in tasks],
        "constant_bytes": const["size"],
        "in": shapes[0][1:],
        "in2": shapes[1][1:],
        "out": shapes[2][1:],
    }


def words_literal(name, words):
    lines = [f"static const uint32_t {name}[] = {{"]
    for off in range(0, len(words), 6):
        chunk = words[off:off + 6]
        lines.append("    " + ", ".join(f"0x{w:08x}" for w in chunk) + ",")
    lines.append("};")
    return lines


def main():
    entries = []
    for path in sorted(CAPTURES.glob("layout_concat_*.json")):
        entry = derive(path)
        if entry is None:
            continue
        entry["stem"] = path.stem
        entries.append(entry)
    if not entries:
        raise SystemExit("no concat captures decoded")
    print(f"verified {len(entries)} entries")

    out = ["// Generated by research/generate_concat_tables.py from",
           "// research/oracles/h13/layout_concat_*.json — do not edit by hand.",
           "#pragma once",
           "",
           "struct H13ConcatTemplate {",
           "    std::uint8_t axis;",
           "    std::uint32_t inChannels, inHeight, inWidth;",
           "    std::uint32_t in2Channels, in2Height, in2Width;",
           "    std::uint32_t outChannels, outHeight, outWidth;",
           "    const std::uint32_t *words;",
           "    std::size_t wordCount;",
           "    std::size_t constantBytes;",
           "    const std::uint32_t *taskWords;",
           "    std::size_t taskCount;",
           "};",
           ""]
    table = []
    for index, entry in enumerate(entries):
        wname = f"kConcatWords{index}"
        sname = f"kConcatSizes{index}"
        out.extend(words_literal(wname, entry["words"]))
        out.append(f"static const uint32_t {sname}[] = "
                   f"{{{', '.join(map(str, entry['sizes']))}}};")
        out.append("")
        in_c, in_h, in_w = entry["in"]
        in2_c, in2_h, in2_w = entry["in2"]
        out_c, out_h, out_w = entry["out"]
        table.append(
            "    {%d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %s, std::size(%s), "
            "%d, %s, std::size(%s)},"
            % (entry["axis"], in_c, in_h, in_w, in2_c, in2_h, in2_w,
               out_c, out_h, out_w, wname, wname, entry["constant_bytes"],
               sname, sname))
    out.append("static const H13ConcatTemplate kConcatTasks[] = {")
    out.extend("    " + row for row in table)
    out.append("};")
    destination = ROOT / "plugins" / "H13" / "H13ConcatTemplates.inc"
    destination.write_text("\n".join(out) + "\n")
    print(f"wrote {destination}")


if __name__ == "__main__":
    main()
